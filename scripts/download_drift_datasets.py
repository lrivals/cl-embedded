#!/usr/bin/env python3
"""
download_drift_datasets.py — Acquisition idempotente des datasets de drift (Sprint 43, S4302).

Vérifie la présence des fichiers bruts attendus dans ``data/raw/<dataset>/`` (jamais committés,
cf. ``.gitignore``), journalise source & licence, et signale ce qui manque avec l'URL officielle.
Les datasets réels sont volumineux et sous licence de recherche → **pas de re-téléchargement
destructeur** : si présents, on se contente de valider et journaliser.

Le synthétique est **généré à la volée** par ``src/data/synthetic_drift_dataset.py`` : rien à
télécharger.

Usage :
    python scripts/download_drift_datasets.py --dataset gas_sensor_drift
    python scripts/download_drift_datasets.py --dataset all
"""

from __future__ import annotations

import argparse
from pathlib import Path

# Métadonnées par dataset : répertoire, fichiers-clés attendus, source, licence, URL officielle.
DATASETS: dict[str, dict] = {
    "gas_sensor_drift": {
        "dir": "data/raw/Gas Sensor Array Drift Dataset",
        "expected": [f"Dataset/batch{i}.dat" for i in range(1, 11)],
        "source": "UCI Gas Sensor Array Drift Dataset (Vergara 2012)",
        "license": "research only — commercial use excluded",
        "url": "https://archive.ics.uci.edu/dataset/224/gas+sensor+array+drift+dataset",
    },
    "hydraulic": {
        "dir": "data/raw/Condition Monitoring of Hydraulic Systems",
        "expected": ["profile.txt", "PS1.txt", "TS1.txt", "FS1.txt", "VS1.txt"],
        "source": "Condition Monitoring of Hydraulic Systems (ZeMA gGmbH / UCI, 2018)",
        "license": "research use (ZeMA gGmbH)",
        "url": "https://archive.ics.uci.edu/dataset/447/condition+monitoring+of+hydraulic+systems",
    },
    "electricity": {
        "dir": "data/raw/The Elec2 Dataset",
        "expected": ["electricity-normalized.csv"],
        "source": "ELEC2 (Harries 1999; Gama 2004; normalized by Bifet)",
        "license": "public / research use",
        "url": "https://www.openml.org/d/151",
    },
    "synthetic": {
        "dir": None,
        "expected": [],
        "source": "numpy synthetic generators (SEA / rotating hyperplane / gradual mixture)",
        "license": "n/a (generated on-the-fly)",
        "url": "n/a — generated by src/data/synthetic_drift_dataset.py",
    },
}


def _check_dataset(name: str, meta: dict) -> bool:
    """Vérifie la présence des fichiers attendus ; journalise source/licence. Retourne OK."""
    print(f"\n=== {name} ===")
    print(f"  source  : {meta['source']}")
    print(f"  licence : {meta['license']}")
    print(f"  url     : {meta['url']}")

    if meta["dir"] is None:  # synthétique
        print("  → généré à la volée, aucun téléchargement requis.")
        return True

    base = Path(meta["dir"])
    if not base.exists():
        print(f"  ✗ répertoire absent : {base}")
        print(f"    → télécharger manuellement depuis {meta['url']} vers {base}/")
        return False

    missing = [f for f in meta["expected"] if not (base / f).exists()]
    if missing:
        print(f"  ✗ fichiers manquants ({len(missing)}) : {missing[:5]}")
        print(f"    → compléter depuis {meta['url']}")
        return False

    print(f"  ✓ présent ({len(meta['expected'])} fichiers-clés vérifiés) : {base}")
    return True


def main() -> None:
    parser = argparse.ArgumentParser(description="Acquisition des datasets de drift (Sprint 43).")
    parser.add_argument(
        "--dataset",
        choices=[*DATASETS.keys(), "all"],
        required=True,
        help="Dataset à vérifier/acquérir.",
    )
    args = parser.parse_args()

    targets = list(DATASETS) if args.dataset == "all" else [args.dataset]
    results = {name: _check_dataset(name, DATASETS[name]) for name in targets}

    print("\n=== Récapitulatif ===")
    for name, ok in results.items():
        print(f"  {'✓' if ok else '✗'} {name}")
    if not all(results.values()):
        print("\nCertains datasets sont incomplets — voir les URLs ci-dessus.")


if __name__ == "__main__":
    main()
